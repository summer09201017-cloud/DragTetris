import type { PieceType, Rotation } from './types';

// Kick tables expressed in grid coordinates (+x = right, +y = DOWN).
// SRS Wiki tables use +y = up; signs flipped here.
type Kicks = Record<string, [number, number][]>;

const JLSTZ_KICKS: Kicks = {
  '0>1': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '1>0': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  '1>2': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  '2>1': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '2>3': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
  '3>2': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '3>0': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '0>3': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]]
};

const I_KICKS: Kicks = {
  '0>1': [[0, 0], [-2, 0], [1, 0], [-2, 1], [1, -2]],
  '1>0': [[0, 0], [2, 0], [-1, 0], [2, -1], [-1, 2]],
  '1>2': [[0, 0], [-1, 0], [2, 0], [-1, -2], [2, 1]],
  '2>1': [[0, 0], [1, 0], [-2, 0], [1, 2], [-2, -1]],
  '2>3': [[0, 0], [2, 0], [-1, 0], [2, -1], [-1, 2]],
  '3>2': [[0, 0], [-2, 0], [1, 0], [-2, 1], [1, -2]],
  '3>0': [[0, 0], [1, 0], [-2, 0], [1, 2], [-2, -1]],
  '0>3': [[0, 0], [-1, 0], [2, 0], [-1, -2], [2, 1]]
};

export function kicksFor(type: PieceType, from: Rotation, to: Rotation): [number, number][] {
  if (type === 'O') return [[0, 0]];
  const key = `${from}>${to}`;
  return type === 'I' ? I_KICKS[key] : JLSTZ_KICKS[key];
}

export function rotateIndex(rot: Rotation, dir: -1 | 1): Rotation {
  return (((rot + dir) % 4) + 4) % 4 as Rotation;
}
